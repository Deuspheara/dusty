//! Dusty's engine: finds what can be cleaned on this Mac, and cleans it safely.
//!
//! No UI lives here: the app and the `dusty` CLI only call this crate's public
//! API. The modules follow one scan → clean flow:
//! - [`scan_all`] walks your projects (`projects`) and the system targets (`targets`), applies the
//!   ignore list and returns [`Target`]s;
//! - [`clean_targets`] removes or trashes them under the safety rules (`clean`) and records each
//!   clean in the history, where [`history::put_back`] can undo it;
//! - [`large`], [`uninstall`] and [`usage`] are the tools; [`schedule`] is the weekly clean.
//!
//! Safety rules:
//! - project folders are only candidates when their parent has a matching marker file, and inside a
//!   git repo only when `git check-ignore` says they are ignored (a tracked `build/` is source code);
//! - deletes only happen under $HOME, never on $HOME/Documents/Library themselves, never through symlinks;
//! - Gradle daemons are stopped before their caches go.

