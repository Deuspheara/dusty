    /// Tests that read or fake $HOME run one at a time.
    static HOME_LOCK: Mutex<()> = Mutex::new(());
    pub(super) fn home_lock() -> std::sync::MutexGuard<'static, ()> {
        HOME_LOCK.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Points $HOME at a fresh temp folder while alive (holding the HOME lock), restores it on drop,
    /// even if the test panics. The folder is removed on drop.
    pub(super) struct FakeHome {
        pub path: PathBuf,
        real: Option<std::ffi::OsString>,
        _lock: std::sync::MutexGuard<'static, ()>,
    }
    impl FakeHome {
        pub fn new(tag: &str) -> Self {
            let lock = home_lock();
            let real = std::env::var_os("HOME");
            // canonical: /var is a symlink to /private/var, and assert_safe compares real locations
            let path = std::fs::canonicalize(tmp_dir(tag)).unwrap();
            unsafe { std::env::set_var("HOME", &path) };
            FakeHome { path, real, _lock: lock }
        }
    }
    impl Drop for FakeHome {
        fn drop(&mut self) {
            match &self.real {
                Some(v) => unsafe { std::env::set_var("HOME", v) },
                None => unsafe { std::env::remove_var("HOME") },
            }
            let _ = std::fs::remove_dir_all(&self.path);
        }
    }

    pub(super) fn tmp_dir(tag: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("dusty-test-{tag}-{}-{:?}", std::process::id(), std::thread::current().id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    pub(super) fn touch(p: &Path, bytes: usize) {
        std::fs::create_dir_all(p.parent().unwrap()).unwrap();
        std::fs::write(p, vec![7u8; bytes]).unwrap();
    }

    pub(super) fn set_old(p: &Path, days: u64) {
        use std::os::unix::ffi::OsStrExt;
        let c = std::ffi::CString::new(p.as_os_str().as_bytes()).unwrap();
        let t = (SystemTime::now() - Duration::from_secs(days * 86400)).duration_since(UNIX_EPOCH).unwrap().as_secs() as libc::time_t;
        let tv = [libc::timeval { tv_sec: t, tv_usec: 0 }, libc::timeval { tv_sec: t, tv_usec: 0 }];
        assert_eq!(unsafe { libc::utimes(c.as_ptr(), tv.as_ptr()) }, 0);
    }

