struct Def {
    id: &'static str,
    label: &'static str,
    group: Group,
    default_on: bool,
    guard: Guard,
    scan: Box<dyn Fn(&[PathBuf]) -> Option<(u64, Vec<PathBuf>, Vec<Cmd>, Option<String>)> + Send + Sync>,
}

/// Simple target: delete whatever paths `resolve` returns (that exist).
fn paths_def(
    id: &'static str,
    label: &'static str,
    group: Group,
    default_on: bool,
    commands: Vec<Cmd>,
    resolve: impl Fn(&[PathBuf]) -> Vec<PathBuf> + Send + Sync + 'static,
) -> Def {
    Def {
        id,
        label,
        group,
        default_on,
        guard: Guard::None,
        scan: Box::new(move |roots| {
            let paths = resolve(roots);
            let sizes = size_of(&paths);
            let existing: Vec<PathBuf> = paths.into_iter().filter(|p| sizes.contains_key(p)).collect();
            if existing.is_empty() {
                return None;
            }
            let bytes = existing.iter().map(|p| sizes[p]).sum();
            Some((bytes, existing, commands.clone(), None))
        }),
    }
}

