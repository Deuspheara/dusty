/// Running-app guard (from Mole): never clean an app's cache while the app is open.
#[derive(Clone, Debug, PartialEq)]
pub enum Guard {
    None,
    /// display name, `pgrep -if` regex matched against running processes
    App(&'static str, &'static str),
    /// path is `…/Application Support/<App>/…`: guard on a running `<App>.app`
    PerAppFolder,
}

impl Target {
    /// Wipes real data (not just cache): worth a louder warning in the UI.
    pub fn wipes_data(&self) -> bool {
        let s = format!("{} {}", self.label, self.id).to_lowercase();
        s.contains('⚠') || s.contains("volume") || s.contains("erase") || s.contains("wipe")
    }
}

