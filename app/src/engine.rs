/// Children of a folder (cleaning a cache folder's contents, not the folder itself, like Mole).
fn contents(dir: &Path) -> Vec<PathBuf> {
    list_dir(dir)
}

/// Files (not folders) directly in `dir`, modified more than `days` ago, whose name passes `keep`.
fn files_older_than(dir: &Path, days: u64, keep: impl Fn(&str) -> bool) -> Vec<PathBuf> {
    list_dir(dir)
        .into_iter()
        .filter(|p| std::fs::symlink_metadata(p).map(|m| m.is_file()).unwrap_or(false))
        .filter(|p| keep(&name_of(p)) && (days == 0 || older_than(p, days)))
        .collect()
}

