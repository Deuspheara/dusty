//! Scanner + cleaner: a port of the `dusty` CLI (src/*.ts) to Rust.
//!
//! Safety rules are the same as the CLI:
//! - project folders are only candidates when their parent has a matching marker file, and inside a
//!   git repo only when `git check-ignore` says they are ignored (a tracked `build/` is source code);
//! - deletes only happen under $HOME, never on $HOME/Documents/Library themselves, never through symlinks;
//! - Gradle daemons are stopped before their caches go.

use std::collections::{HashMap, HashSet};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

// ───────────────────────── model ─────────────────────────

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Group {
    Build,
    Apps,
    Cache,
    Junk,
    Docker,
    Redownload,
}

impl Group {
    pub const ORDER: [Group; 6] = [Group::Build, Group::Apps, Group::Cache, Group::Junk, Group::Docker, Group::Redownload];
    pub fn name(self) -> &'static str {
        match self {
            Group::Build => "Build leftovers",
            Group::Apps => "App & browser caches",
            Group::Cache => "Dev caches",
            Group::Junk => "Logs & leftovers",
            Group::Docker => "Docker",
            Group::Redownload => "Needs re-download",
        }
    }
    pub fn blurb(self) -> &'static str {
        match self {
            Group::Build => "Regenerated by your next build",
            Group::Apps => "Each app rebuilds them; skipped while it's open",
            Group::Cache => "Rebuilt locally, nothing to download",
            Group::Junk => "Old logs, crash reports, unfinished downloads",
            Group::Docker => "Build cache and stopped containers",
            Group::Redownload => "Opt-in: costs a download later",
        }
    }
}

#[derive(Clone, Debug)]
pub struct Cmd {
    pub cmd: String,
    pub args: Vec<String>,
}

fn cmd(c: &str, args: &[&str]) -> Cmd {
    Cmd { cmd: c.into(), args: args.iter().map(|s| s.to_string()).collect() }
}

#[derive(Clone, Debug)]
pub struct Target {
    pub id: String,
    pub label: String,
    pub group: Group,
    pub default_on: bool,
    pub bytes: u64,
    pub paths: Vec<PathBuf>,
    pub commands: Vec<Cmd>,
    pub detail: Option<String>,
    /// Skip (and report) paths whose app is running: deleting a live cache can break the app.
    pub guard: Guard,
}

/// Running-app guard (from Mole): never clean an app's cache while the app is open.
#[derive(Clone, Debug, PartialEq)]
pub enum Guard {
    None,
    /// display name, `pgrep -if` regex matched against running processes
    App(&'static str, &'static str),
    /// path is `…/Application Support/<App>/…`: guard on a running `<App>.app`
    PerAppFolder,
}

impl Target {
    /// Wipes real data (not just cache): worth a louder warning in the UI.
    pub fn wipes_data(&self) -> bool {
        let s = format!("{} {}", self.label, self.id).to_lowercase();
        s.contains('⚠') || s.contains("volume") || s.contains("erase") || s.contains("wipe")
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Disk {
    pub total: u64,
    pub free: u64,
}

/// Live scan progress, shared with the UI thread.
#[derive(Default)]
pub struct ScanProgress {
    pub message: String,
    pub found: Vec<Target>,
    pub done: bool,
}

// ───────────────────────── utils ─────────────────────────

pub fn home() -> PathBuf {
    std::env::var_os("HOME").map(PathBuf::from).unwrap_or_else(|| PathBuf::from("/"))
}
fn h(p: &str) -> PathBuf {
    home().join(p)
}

/// Apps launched from Finder get a bare PATH; add the usual tool locations so brew/docker/xcrun resolve.
pub fn fix_path() {
    let cur = std::env::var("PATH").unwrap_or_default();
    let extra = ["/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin"];
    let mut parts: Vec<String> = cur.split(':').filter(|s| !s.is_empty()).map(String::from).collect();
    for e in extra.iter().rev() {
        if !parts.iter().any(|p| p == e) {
            parts.insert(0, e.to_string());
        }
    }
    let cargo = h(".cargo/bin");
    parts.push(cargo.to_string_lossy().into());
    // SAFETY: called once at startup before any threads are spawned.
    unsafe { std::env::set_var("PATH", parts.join(":")) };
}

pub struct RunResult {
    pub ok: bool,
    pub stdout: String,
    pub stderr: String,
}

/// Run a command with a timeout. Never panics; a missing binary is just `ok: false`.
pub fn run(program: &str, args: &[String], timeout: Duration, stdin: Option<&str>) -> RunResult {
    let mut c = Command::new(program);
    c.args(args).stdout(Stdio::piped()).stderr(Stdio::piped());
    c.stdin(if stdin.is_some() { Stdio::piped() } else { Stdio::null() });
    let mut child = match c.spawn() {
        Ok(ch) => ch,
        Err(e) => return RunResult { ok: false, stdout: String::new(), stderr: e.to_string() },
    };
    if let (Some(input), Some(mut sin)) = (stdin, child.stdin.take()) {
        let input = input.to_string();
        std::thread::spawn(move || {
            let _ = sin.write_all(input.as_bytes());
        });
    }
    // drain pipes on threads so a chatty child can't deadlock on a full pipe
    let mut out = child.stdout.take();
    let mut err = child.stderr.take();
    let to = std::thread::spawn(move || {
        let mut s = String::new();
        if let Some(o) = out.as_mut() {
            let _ = std::io::Read::read_to_string(o, &mut s);
        }
        s
    });
    let te = std::thread::spawn(move || {
        let mut s = String::new();
        if let Some(e) = err.as_mut() {
            let _ = std::io::Read::read_to_string(e, &mut s);
        }
        s
    });
    let start = Instant::now();
    let status = loop {
        match child.try_wait() {
            Ok(Some(st)) => break Some(st),
            Ok(None) if start.elapsed() > timeout => {
                let _ = child.kill();
                let _ = child.wait();
                break None;
            }
            Ok(None) => std::thread::sleep(Duration::from_millis(15)),
            Err(_) => break None,
        }
    };
    let stdout = to.join().unwrap_or_default();
    let stderr = te.join().unwrap_or_default();
    RunResult { ok: status.map(|s| s.success()).unwrap_or(false), stdout, stderr }
}

fn run_s(program: &str, args: &[&str], secs: u64) -> RunResult {
    let a: Vec<String> = args.iter().map(|s| s.to_string()).collect();
    run(program, &a, Duration::from_secs(secs), None)
}

fn which(bin: &str) -> bool {
    run_s("/usr/bin/which", &[bin], 10).ok
}

fn is_dir(p: &Path) -> bool {
    std::fs::symlink_metadata(p).map(|m| m.is_dir()).unwrap_or(false)
}
fn exists(p: &Path) -> bool {
    std::fs::symlink_metadata(p).is_ok()
}

fn list_dir(p: &Path) -> Vec<PathBuf> {
    match std::fs::read_dir(p) {
        Ok(rd) => rd.filter_map(|e| e.ok().map(|e| e.path())).collect(),
        Err(_) => vec![],
    }
}

fn children(dir: &Path, exclude: impl Fn(&str) -> bool) -> Vec<PathBuf> {
    list_dir(dir).into_iter().filter(|p| !exclude(&name_of(p))).collect()
}

fn name_of(p: &Path) -> String {
    p.file_name().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default()
}

/// Real on-disk sizes via `du -skx` (APFS clones and sparse files counted right, never crosses volumes).
pub fn size_of(paths: &[PathBuf]) -> HashMap<PathBuf, u64> {
    let out = Mutex::new(HashMap::new());
    let chunks: Vec<&[PathBuf]> = paths.chunks(200).collect();
    let next = AtomicUsize::new(0);
    std::thread::scope(|s| {
        for _ in 0..4.min(chunks.len().max(1)) {
            s.spawn(|| loop {
                let i = next.fetch_add(1, Ordering::SeqCst);
                let Some(chunk) = chunks.get(i) else { break };
                let mut args = vec!["-skx".to_string()];
                args.extend(chunk.iter().map(|p| p.to_string_lossy().into_owned()));
                let r = run("/usr/bin/du", &args, Duration::from_secs(600), None);
                let mut map = out.lock().unwrap();
                for line in r.stdout.lines() {
                    if let Some((kb, path)) = line.split_once('\t') {
                        if let Ok(kb) = kb.trim().parse::<u64>() {
                            map.insert(PathBuf::from(path), kb * 1024);
                        }
                    }
                }
            });
        }
    });
    out.into_inner().unwrap()
}

fn total_size(paths: &[PathBuf]) -> u64 {
    size_of(paths).values().sum()
}

pub fn format_bytes(b: u64) -> String {
    if b < 1024 {
        return format!("{b} B");
    }
    let units = ["KB", "MB", "GB", "TB"];
    let mut v = b as f64 / 1024.0;
    let mut u = 0;
    while v >= 1024.0 && u < units.len() - 1 {
        v /= 1024.0;
        u += 1;
    }
    if v >= 100.0 { format!("{:.0} {}", v, units[u]) } else { format!("{:.1} {}", v, units[u]) }
}

/// "6.745GB", "512MB", "0B" → bytes (docker uses SI units)
fn parse_docker_size(s: &str) -> u64 {
    let s = s.trim();
    let num: String = s.chars().take_while(|c| c.is_ascii_digit() || *c == '.').collect();
    let unit = s[num.len()..].trim().to_uppercase();
    let n: f64 = num.parse().unwrap_or(0.0);
    let m = if unit.starts_with("TB") { 1e12 } else if unit.starts_with("GB") { 1e9 } else if unit.starts_with("MB") { 1e6 } else if unit.starts_with("KB") { 1e3 } else { 1.0 };
    (n * m) as u64
}

pub fn disk() -> Disk {
    use std::ffi::CString;
    let path = CString::new("/System/Volumes/Data").unwrap();
    let mut st: libc::statfs = unsafe { std::mem::zeroed() };
    if unsafe { libc::statfs(path.as_ptr(), &mut st) } == 0 {
        let bs = st.f_bsize as u64;
        Disk { total: st.f_blocks as u64 * bs, free: st.f_bavail as u64 * bs }
    } else {
        Disk { total: 1, free: 0 }
    }
}

pub fn tildify(p: &Path) -> String {
    let hs = home().to_string_lossy().into_owned();
    let s = p.to_string_lossy();
    if let Some(rest) = s.strip_prefix(&hs) { format!("~{rest}") } else { s.into_owned() }
}

fn mtime(p: &Path) -> SystemTime {
    std::fs::symlink_metadata(p).and_then(|m| m.modified()).unwrap_or(UNIX_EPOCH)
}

fn older_than(p: &Path, days: u64) -> bool {
    SystemTime::now().duration_since(mtime(p)).map(|d| d > Duration::from_secs(days * 86400)).unwrap_or(false)
}

/// Days since 1970-01-01 for an ISO date "YYYY-MM-DD…" (civil-from-days inverse).
fn iso_days(s: &str) -> Option<i64> {
    let y: i64 = s.get(0..4)?.parse().ok()?;
    let m: i64 = s.get(5..7)?.parse().ok()?;
    let d: i64 = s.get(8..10)?.parse().ok()?;
    let y2 = if m <= 2 { y - 1 } else { y };
    let era = if y2 >= 0 { y2 } else { y2 - 399 } / 400;
    let yoe = y2 - era * 400;
    let doy = (153 * (if m > 2 { m - 3 } else { m + 9 }) + 2) / 5 + d - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    Some(era * 146097 + doe - 719468)
}

fn now_days() -> i64 {
    (SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default().as_secs() / 86400) as i64
}

/// Version-like descending sort on the file name ("1.10" > "1.9").
fn by_version_desc(a: &PathBuf, b: &PathBuf) -> std::cmp::Ordering {
    natural_cmp(&name_of(b), &name_of(a))
}
fn natural_cmp(a: &str, b: &str) -> std::cmp::Ordering {
    let split = |s: &str| -> Vec<(bool, String)> {
        let mut out: Vec<(bool, String)> = vec![];
        for c in s.chars() {
            let dig = c.is_ascii_digit();
            match out.last_mut() {
                Some((d, buf)) if *d == dig => buf.push(c),
                _ => out.push((dig, c.to_string())),
            }
        }
        out
    };
    let (x, y) = (split(a), split(b));
    for (p, q) in x.iter().zip(y.iter()) {
        let o = if p.0 && q.0 {
            p.1.trim_start_matches('0').len().cmp(&q.1.trim_start_matches('0').len()).then(p.1.cmp(&q.1))
        } else {
            p.1.to_lowercase().cmp(&q.1.to_lowercase())
        };
        if o != std::cmp::Ordering::Equal {
            return o;
        }
    }
    x.len().cmp(&y.len())
}

fn all_but_newest(dir: &Path, keep: usize) -> Vec<PathBuf> {
    let mut dirs: Vec<PathBuf> = list_dir(dir).into_iter().filter(|p| is_dir(p)).collect();
    dirs.sort_by(by_version_desc);
    dirs.into_iter().skip(keep).collect()
}

