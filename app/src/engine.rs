#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum Group {
    Build,
    Apps,
    Cache,
    Junk,
    Docker,
    Redownload,
}

impl Group {
    pub const ORDER: [Group; 6] = [Group::Build, Group::Apps, Group::Cache, Group::Junk, Group::Docker, Group::Redownload];
    pub fn name(self) -> &'static str {
        match self {
            Group::Build => "Build leftovers",
            Group::Apps => "App & browser caches",
            Group::Cache => "Dev caches",
            Group::Junk => "Logs & leftovers",
            Group::Docker => "Docker",
            Group::Redownload => "Needs re-download",
        }
    }
    pub fn blurb(self) -> &'static str {
        match self {
            Group::Build => "Regenerated by your next build",
            Group::Apps => "Each app rebuilds them; skipped while it's open",
            Group::Cache => "Rebuilt locally, nothing to download",
            Group::Junk => "Old logs, crash reports, unfinished downloads",
            Group::Docker => "Build cache and stopped containers",
            Group::Redownload => "Opt-in: costs a download later",
        }
    }
}

