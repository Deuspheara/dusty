//! Scanner + cleaner: a port of the `dusty` CLI (src/*.ts) to Rust.
//!
//! Safety rules are the same as the CLI:
//! - project folders are only candidates when their parent has a matching marker file, and inside a
//!   git repo only when `git check-ignore` says they are ignored (a tracked `build/` is source code);
//! - deletes only happen under $HOME, never on $HOME/Documents/Library themselves, never through symlinks;
//! - Gradle daemons are stopped before their caches go.

use std::collections::{HashMap, HashSet};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicBool, AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

