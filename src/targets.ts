export type Group = "build" | "cache" | "docker" | "redownload";

export const GROUP_LABELS: Record<Group, string> = {
  build: "Project build artifacts (regenerated by next build)",
  cache: "Dev tool caches (rebuilt locally, no download)",
  docker: "Docker",
  redownload: "Needs re-download (opt-in)",
};

export interface Command {
  cmd: string;
  args: string[];
}

export interface Target {
  id: string;
  label: string;
  group: Group;
  defaultOn: boolean;
  bytes: number;
  /** Folders/files to delete. */
  paths: string[];
  /** Commands to run (before path deletion). */
  commands: Command[];
  detail?: string;
}

export interface TargetDef {
  id: string;
  label: string;
  group: Group;
  defaultOn: boolean;
  scan: (ctx: ScanContext) => Promise<Omit<Target, "id" | "label" | "group" | "defaultOn"> | null>;
}

export interface ScanContext {
  /** Folders scanned for projects (used to find which SDK versions are still referenced). */
  roots: string[];
}

/** Simple target: delete everything matched by a list of paths (globbed by children). */
export function pathsTarget(
  def: Omit<TargetDef, "scan">,
  resolve: (ctx: ScanContext) => Promise<string[]>,
  extra?: { commands?: Command[]; detail?: string },
): TargetDef {
  return {
    ...def,
    scan: async (ctx) => {
      const paths = await resolve(ctx);
      const sizes = await sizeOf(paths);
      const existing = paths.filter((p) => sizes.has(p));
      const bytes = existing.reduce((s, p) => s + (sizes.get(p) ?? 0), 0);
      if (existing.length === 0) return null;
      return { bytes, paths: existing, commands: extra?.commands ?? [], detail: extra?.detail };
    },
  };
}

export const children = async (dir: string, exclude: (name: string) => boolean = () => false) =>
  (await listDir(dir)).filter((p) => !exclude(path.basename(p)));

