function dockerTargets(): TargetDef[] {
  let dfCache: Promise<Record<string, number> | null> | null = null;
  const df = () =>
    (dfCache ??= (async () => {
      if (!(await which("docker"))) return null;
      const info = await run("docker", ["info", "--format", "{{.ServerVersion}}"], 15_000);
      if (!info.ok) return null; // daemon not running
      const res = await run("docker", ["system", "df", "--format", "{{json .}}"], 60_000);
      if (!res.ok) return null;
      const out: Record<string, number> = {};
      for (const line of res.stdout.trim().split("\n")) {
        try {
          const j = JSON.parse(line) as { Type: string; Reclaimable: string };
          out[j.Type] = parseDockerSize(j.Reclaimable);
        } catch {}
      }
      return out;
    })());

  const t = (id: string, label: string, type: string, defaultOn: boolean, args: string[]): TargetDef => ({
    id,
    label,
    group: "docker",
    defaultOn,
    scan: async () => {
      const d = await df();
      if (!d || !(type in d)) return null;
      return { bytes: d[type], paths: [], commands: [{ cmd: "docker", args }] };
    },
  });

  return [
    t("docker-buildcache", "Docker build cache", "Build Cache", true, ["builder", "prune", "-af"]),
    t("docker-containers", "Docker stopped containers", "Containers", true, ["container", "prune", "-f"]),
    t("docker-images", "Docker unused images", "Images", false, ["image", "prune", "-af"]),
    t("docker-volumes", "Docker volumes ⚠ data", "Local Volumes", false, ["volume", "prune", "-af"]),
  ];
}

export async function scanTargets(ctx: ScanContext, onProgress?: (label: string) => void): Promise<Target[]> {
  const results = await Promise.all(
    TARGET_DEFS.map(async (def) => {
      try {
        const r = await def.scan(ctx);
        onProgress?.(def.label);
        if (!r) return null;
        return { id: def.id, label: def.label, group: def.group, defaultOn: def.defaultOn, ...r } satisfies Target;
      } catch {
        return null;
      }
    }),
  );
  return results.filter((r): r is Target => r !== null);
}
